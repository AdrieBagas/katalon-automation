@Keyword
def FileDownload(String path, String fileName, int timeoutSeconds) {
	String folderPath = path
	File file = new File(folderPath + "\\" + fileName)

	for (int i = 0; i < timeoutSeconds; i++) {
		if (file.exists()) {
			KeywordUtil.markPassed("Download selesai!")
			return true
		}
		WebUI.delay(1)
	}
	KeywordUtil.markFailed("Timeout: File tidak selesai terdownload.")
	return false
}

